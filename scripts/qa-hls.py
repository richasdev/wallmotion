#!/usr/bin/env python3
"""Opt-in synthetic HLS observation; no app launch or external media."""
import argparse
import http.server
import json
import os
import platform
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import threading

ROOT = Path(__file__).resolve().parent.parent


def run(command, timeout=60):
    result = subprocess.run(command, capture_output=True, text=True, timeout=timeout)
    if result.returncode:
        raise RuntimeError(f"{Path(command[0]).name} failed ({result.returncode})")
    return result.stdout


def make_assets(root, ffmpeg):
    layouts = {
        "landscape": [(640, 360, 300_000), (1920, 1080, 3_000_000)],
        "portrait": [(360, 640, 300_000), (720, 1280, 1_500_000)],
    }
    for orientation, variants in layouts.items():
        master = ["#EXTM3U", "#EXT-X-VERSION:3", "#EXT-X-INDEPENDENT-SEGMENTS"]
        for index, (width, height, bitrate) in enumerate(variants):
            folder = root / orientation / str(index)
            folder.mkdir(parents=True)
            run([ffmpeg, "-nostdin", "-hide_banner", "-loglevel", "error", "-f", "lavfi", "-i",
                 f"testsrc2=size={width}x{height}:rate=12", "-t", "8", "-an", "-c:v", "libx264",
                 "-preset", "ultrafast", "-threads", "2", "-pix_fmt", "yuv420p", "-g", "12",
                 "-keyint_min", "12", "-sc_threshold", "0", "-b:v", str(bitrate),
                 "-hls_time", "1", "-hls_list_size", "0", "-hls_playlist_type", "vod",
                 "-hls_flags", "independent_segments", "-hls_segment_filename",
                 str(folder / "segment-%03d.ts"), str(folder / "index.m3u8")], timeout=30)
            master.extend([f"#EXT-X-STREAM-INF:BANDWIDTH={bitrate},RESOLUTION={width}x{height}",
                           f"{index}/index.m3u8"])
        (root / orientation / "master.m3u8").write_text("\n".join(master) + "\n")
    return layouts


class Handler(http.server.BaseHTTPRequestHandler):
    def log_message(self, *args):
        pass

    def do_GET(self):
        # Exact generated assets only: no directory listing, traversal or redirects.
        path = self.path
        payload = self.server.assets.get(path)
        if payload is None:
            self.send_error(404)
            return
        data, mime = payload
        with self.server.count_lock:
            self.server.counts[path] = self.server.counts.get(path, 0) + 1
        self.send_response(200)
        self.send_header("Content-Type", mime)
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        try:
            self.wfile.write(data)
        except (BrokenPipeError, ConnectionResetError):
            pass


class Server(http.server.HTTPServer):
    # One bounded request handler; the fixture does not need an unbounded thread pool.
    allow_reuse_address = False

    def get_request(self):
        connection, address = super().get_request()
        connection.settimeout(3)
        return connection, address


def load_assets(root):
    # Immutable generated bytes avoid exposing the checkout or arbitrary files.
    assets = {}
    remaining = 32 * 1024 * 1024
    for path in root.rglob("*"):
        if path.suffix not in (".m3u8", ".ts"):
            continue
        if path.stat().st_size > remaining:
            raise RuntimeError("generated assets exceed the 32 MiB fixture allowance")
        data = path.read_bytes()
        if len(data) > remaining:
            raise RuntimeError("generated assets changed beyond the fixture allowance")
        remaining -= len(data)
        mime = "application/vnd.apple.mpegurl" if path.suffix == ".m3u8" else "video/mp2t"
        assets["/" + path.relative_to(root).as_posix()] = (data, mime)
    return assets


def observe(binary, assets, orientation, width, height, duration):
    with Server(("127.0.0.1", 0), Handler) as server:
        server.assets = assets
        server.counts = {}
        server.count_lock = threading.Lock()
        thread = threading.Thread(target=server.serve_forever, kwargs={"poll_interval": 0.05}, daemon=True)
        thread.start()
        try:
            port = server.server_address[1]
            report = json.loads(run([str(binary), f"http://127.0.0.1:{port}/{orientation}/master.m3u8",
                                     str(width), str(height), str(duration)], timeout=duration + 15))
        finally:
            server.shutdown()
            thread.join(timeout=2)
        with server.count_lock:
            counts = dict(server.counts)
    report["orientation"] = orientation
    report["requests_by_variant"] = {
        str(index): sum(count for path, count in counts.items() if path.startswith(f"/{orientation}/{index}/"))
        for index in range(2)
    }
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run", action="store_true", help="Explicitly permit local fixture generation and loopback playback")
    parser.add_argument("--duration", type=float, default=5, help="Seconds per case (1...7)")
    parser.add_argument("--output", type=Path, help="Create-only JSON report; defaults to stdout")
    args = parser.parse_args()
    if not args.run:
        parser.error("--run is required before any build, server or playback")
    if not 1 <= args.duration <= 7:
        parser.error("--duration must be finite and between 1 and 7")
    if args.output and (args.output.exists() or args.output.is_symlink()):
        parser.error("--output must not already exist")
    if sys.platform != "darwin":
        parser.error("macOS is required")
    ffmpeg = shutil.which("ffmpeg")
    swiftc = shutil.which("swiftc")
    if not ffmpeg or not swiftc:
        parser.error("ffmpeg with libx264 and swiftc are required")
    with tempfile.TemporaryDirectory(prefix="wallmotion-hls-qa-") as directory:
        root = Path(directory)
        assets = root / "assets"
        layouts = make_assets(assets, ffmpeg)
        payloads = load_assets(assets)
        binary = root / "probe"
        run([swiftc, "-parse-as-library", str(ROOT / "Tests/Fixtures/hls-probe.swift"), "-o", str(binary)])
        cases = []
        for orientation in layouts:
            for width, height in [(0, 0), (1280, 720)]:
                print(f"Observing {orientation}, preference {width}x{height}", file=sys.stderr, flush=True)
                cases.append(observe(binary, payloads, orientation, width, height, args.duration))
        report = {"schema": 1, "macos": platform.mac_ver()[0], "architecture": platform.machine(), "fixture": "synthetic-h264-sdr-loopback", "variants": layouts,
                  "cases": cases, "status": "observed" if all(c["status"] == "observed" for c in cases) else "incomplete"}
    encoded = json.dumps(report, indent=2, allow_nan=False) + "\n"
    if args.output:
        descriptor = os.open(args.output, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(descriptor, "w") as file:
            file.write(encoded)
    else:
        print(encoded, end="")
    return 0 if report["status"] == "observed" else 2


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, ValueError, RuntimeError, subprocess.SubprocessError) as error:
        print(f"HLS QA failed: {type(error).__name__}: {error}", file=sys.stderr)
        sys.exit(2)
